"""Machine-readable conditional mathematical claims and their proof status.

Unit tests are numerical/software checks, never formal proofs. Registry scope
is finite declared models, not universal statements about resource technology.
"""

from dataclasses import asdict, dataclass


@dataclass(frozen=True)
class Proposition:
    identifier: str
    statement: str
    assumptions: tuple[str, ...]
    proof_status: str
    proof: str
    implementation_relation: str
    validation_tests: tuple[str, ...]
    scope: str
    counterexamples: tuple[str, ...] = ()


def _claim(
    identifier,
    statement,
    assumptions,
    proof,
    implementation,
    tests=(),
    counterexamples=(),
    status="analytic_proof_sketch",
    scope="declared finite models only",
):
    return Proposition(
        identifier,
        statement,
        tuple(assumptions),
        status,
        proof,
        implementation,
        tuple(tests),
        scope,
        tuple(counterexamples),
    )


